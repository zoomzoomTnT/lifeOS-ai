package com.lifeos.db.libsql;

import java.io.IOException;
import java.io.InputStream;
import java.io.Reader;
import java.math.BigDecimal;
import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.SQLFeatureNotSupportedException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.sql.Time;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Calendar;
import java.util.List;

/** Statement + PreparedStatement implementation (exposed through {@link JdbcProxy}). */
final class LibSqlStatement {

    private final LibSqlConnection conn;
    private final String sql; // null for a plain Statement
    private final int resultSetType;
    private final int autoGeneratedKeys;
    private final String keyColumnName;
    // per execution: plain Statement.execute*(sql, keys) can ask for keys too
    private boolean wantKeys;
    private String keyName;
    private Statement self;

    private final List<Object> params = new ArrayList<>();
    private final List<List<Object>> batchParams = new ArrayList<>();
    private final List<String> batchSql = new ArrayList<>();
    private boolean closed;
    private boolean closeOnCompletion;
    private ResultSet currentResultSet;
    private long updateCount = -1;
    private StmtResult lastResult;
    private long maxRows;
    private int queryTimeout;
    private int fetchSize;
    private int fetchDirection = ResultSet.FETCH_FORWARD;
    private boolean poolable = true;

    LibSqlStatement(LibSqlConnection conn, String sql, int resultSetType, int autoGeneratedKeys, String keyColumnName) {
        this.conn = conn;
        this.sql = sql;
        this.resultSetType = resultSetType;
        this.autoGeneratedKeys = autoGeneratedKeys;
        this.keyColumnName = keyColumnName;
        this.wantKeys = autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS;
        this.keyName = keyColumnName;
    }

    Statement statementProxy() {
        if (self == null) self = JdbcProxy.create(Statement.class, this);
        return self;
    }

    PreparedStatement preparedProxy() {
        if (self == null) self = JdbcProxy.create(PreparedStatement.class, this);
        return (PreparedStatement) self;
    }

    /** Generated keys are SQLite's last_insert_rowid: only one key column can be reported. */
    static void checkKeyColumns(int n) throws SQLException {
        if (n > 1) {
            throw new SQLFeatureNotSupportedException("only one generated key column (the rowid) is supported");
        }
    }

    // ---------------------------------------------------------------- execution

    private boolean run(String text, List<Object> args) throws SQLException {
        checkOpen();
        if (text == null) throw new SQLException("no SQL given");
        closeCurrentResultSet();
        StmtResult r = conn.execute(text, args);
        lastResult = r;
        if (r.hasColumns()) {
            List<Object[]> rows = r.rows();
            if (maxRows > 0 && rows.size() > maxRows) rows = rows.subList(0, (int) maxRows);
            currentResultSet = new LibSqlResultSet(statementProxyAny(), r.columns(), r.declTypes(), rows,
                    resultSetType).proxy();
            updateCount = -1;
            return true;
        }
        updateCount = r.affectedRows();
        return false;
    }

    private Statement statementProxyAny() {
        return self != null ? self : statementProxy();
    }

    private void requirePrepared() throws SQLException {
        if (sql == null) throw new SQLException("not a PreparedStatement");
    }

    private void requirePlain() throws SQLException {
        if (sql != null) throw new SQLException("PreparedStatement: use the no-argument execute methods");
    }

    public boolean execute() throws SQLException {
        requirePrepared();
        return run(sql, new ArrayList<>(params));
    }

    public ResultSet executeQuery() throws SQLException {
        execute();
        return resultSetOrEmpty();
    }

    public int executeUpdate() throws SQLException {
        return (int) executeLargeUpdate();
    }

    public long executeLargeUpdate() throws SQLException {
        execute();
        return lastResult.affectedRows();
    }

    public boolean execute(String text) throws SQLException {
        return execute(text, Statement.NO_GENERATED_KEYS);
    }

    public boolean execute(String text, int keys) throws SQLException {
        requirePlain();
        if (keys != Statement.RETURN_GENERATED_KEYS && keys != Statement.NO_GENERATED_KEYS) {
            throw new SQLException("invalid autoGeneratedKeys: " + keys);
        }
        wantKeys = keys == Statement.RETURN_GENERATED_KEYS;
        keyName = null;
        return run(text, List.of());
    }

    public boolean execute(String text, int[] cols) throws SQLException {
        checkKeyColumns(cols == null ? 0 : cols.length);
        requirePlain();
        wantKeys = true;
        keyName = null;
        return run(text, List.of());
    }

    public boolean execute(String text, String[] cols) throws SQLException {
        checkKeyColumns(cols == null ? 0 : cols.length);
        requirePlain();
        wantKeys = true;
        keyName = cols == null || cols.length == 0 ? null : cols[0];
        return run(text, List.of());
    }

    public ResultSet executeQuery(String text) throws SQLException {
        execute(text);
        return resultSetOrEmpty();
    }

    public int executeUpdate(String text) throws SQLException {
        execute(text);
        return (int) lastResult.affectedRows();
    }

    public int executeUpdate(String text, int keys) throws SQLException {
        execute(text, keys);
        return (int) lastResult.affectedRows();
    }

    public int executeUpdate(String text, int[] cols) throws SQLException {
        execute(text, cols);
        return (int) lastResult.affectedRows();
    }

    public int executeUpdate(String text, String[] cols) throws SQLException {
        execute(text, cols);
        return (int) lastResult.affectedRows();
    }

    public long executeLargeUpdate(String text, int keys) throws SQLException {
        execute(text, keys);
        return lastResult.affectedRows();
    }

    public long executeLargeUpdate(String text) throws SQLException {
        execute(text);
        return lastResult.affectedRows();
    }

    private ResultSet resultSetOrEmpty() throws SQLException {
        if (currentResultSet == null) {
            currentResultSet = new LibSqlResultSet(statementProxyAny(), List.of(), List.of(), List.of(),
                    resultSetType).proxy();
        }
        return currentResultSet;
    }

    // ---------------------------------------------------------------- batches

    public void addBatch() throws SQLException {
        requirePrepared();
        checkOpen();
        batchParams.add(new ArrayList<>(params));
    }

    public void addBatch(String text) throws SQLException {
        requirePlain();
        checkOpen();
        batchSql.add(text);
    }

    public void clearBatch() {
        batchParams.clear();
        batchSql.clear();
    }

    public int[] executeBatch() throws SQLException {
        long[] l = executeLargeBatch();
        return Arrays.stream(l).mapToInt(x -> (int) x).toArray();
    }

    public long[] executeLargeBatch() throws SQLException {
        checkOpen();
        int n = sql != null ? batchParams.size() : batchSql.size();
        long[] counts = new long[n];
        int done = 0;
        try {
            for (int i = 0; i < n; i++) {
                if (sql != null) run(sql, batchParams.get(i));
                else run(batchSql.get(i), List.of());
                counts[i] = lastResult.affectedRows();
                done++;
            }
        } catch (SQLException e) {
            throw new BatchUpdateException(e.getMessage(), e.getSQLState(), e.getErrorCode(),
                    Arrays.stream(Arrays.copyOf(counts, done)).mapToInt(x -> (int) x).toArray(), e);
        } finally {
            clearBatch();
        }
        return counts;
    }

    // ---------------------------------------------------------------- results

    public ResultSet getResultSet() throws SQLException {
        checkOpen();
        return currentResultSet;
    }

    public int getUpdateCount() throws SQLException {
        checkOpen();
        return (int) updateCount;
    }

    public long getLargeUpdateCount() throws SQLException {
        checkOpen();
        return updateCount;
    }

    public boolean getMoreResults() throws SQLException {
        closeCurrentResultSet();
        updateCount = -1;
        return false;
    }

    public boolean getMoreResults(int current) throws SQLException {
        return getMoreResults();
    }

    /** last_insert_rowid of the last write, when generated keys were requested; else empty. */
    public ResultSet getGeneratedKeys() throws SQLException {
        checkOpen();
        List<Object[]> rows = new ArrayList<>();
        if (wantKeys && lastResult != null
                && lastResult.lastInsertRowid() != null && lastResult.affectedRows() > 0) {
            rows.add(new Object[]{lastResult.lastInsertRowid()});
        }
        String name = keyName != null ? keyName : "id";
        return new LibSqlResultSet(statementProxyAny(), List.of(name), Arrays.asList((String) null), rows,
                ResultSet.TYPE_FORWARD_ONLY).proxy();
    }

    public ResultSetMetaData getMetaData() {
        return null; // unknown before execution (allowed by JDBC)
    }

    private void closeCurrentResultSet() throws SQLException {
        if (currentResultSet != null) {
            ResultSet rs = currentResultSet;
            currentResultSet = null;
            rs.close();
        }
    }

    // ---------------------------------------------------------------- parameters

    private void set(int index, Object value) throws SQLException {
        requirePrepared();
        checkOpen();
        if (index < 1) throw new SQLException("parameter index starts at 1: " + index);
        while (params.size() < index) params.add(null);
        params.set(index - 1, value);
    }

    public void clearParameters() {
        params.clear();
    }

    public void setNull(int i, int sqlType) throws SQLException { set(i, null); }
    public void setNull(int i, int sqlType, String typeName) throws SQLException { set(i, null); }
    public void setBoolean(int i, boolean v) throws SQLException { set(i, v); }
    public void setByte(int i, byte v) throws SQLException { set(i, v); }
    public void setShort(int i, short v) throws SQLException { set(i, v); }
    public void setInt(int i, int v) throws SQLException { set(i, v); }
    public void setLong(int i, long v) throws SQLException { set(i, v); }
    public void setFloat(int i, float v) throws SQLException { set(i, v); }
    public void setDouble(int i, double v) throws SQLException { set(i, v); }
    public void setBigDecimal(int i, BigDecimal v) throws SQLException { set(i, v); }
    public void setString(int i, String v) throws SQLException { set(i, v); }
    public void setNString(int i, String v) throws SQLException { set(i, v); }
    public void setBytes(int i, byte[] v) throws SQLException { set(i, v); }
    // Date/time are stored as ISO-8601 TEXT, always with seconds:
    //   Timestamp / Instant          -> UTC instant, e.g. 2026-10-10T03:00:00Z (zone-independent)
    //   OffsetDateTime / ZonedDateTime -> with its offset, e.g. 2026-10-10T12:00:00+09:00
    //   LocalDateTime / LocalDate / LocalTime -> wall time as given (no zone)
    //   java.sql.Date / Time         -> local date / time in the JVM zone, or the Calendar's zone
    public void setDate(int i, Date v) throws SQLException { set(i, v == null ? null : v.toLocalDate().toString()); }
    public void setDate(int i, Date v, Calendar c) throws SQLException {
        if (v == null || c == null) { setDate(i, v); return; }
        set(i, java.time.Instant.ofEpochMilli(v.getTime()).atZone(c.getTimeZone().toZoneId()).toLocalDate().toString());
    }
    public void setTime(int i, Time v) throws SQLException {
        set(i, v == null ? null : java.time.format.DateTimeFormatter.ISO_LOCAL_TIME.format(v.toLocalTime()));
    }
    public void setTime(int i, Time v, Calendar c) throws SQLException {
        if (v == null || c == null) { setTime(i, v); return; }
        set(i, java.time.format.DateTimeFormatter.ISO_LOCAL_TIME.format(
                java.time.Instant.ofEpochMilli(v.getTime()).atZone(c.getTimeZone().toZoneId()).toLocalTime()));
    }
    public void setTimestamp(int i, Timestamp v) throws SQLException {
        set(i, v == null ? null : v.toInstant().toString());
    }
    /** A Timestamp is an instant; stored as UTC it is the same value whatever the Calendar's zone. */
    public void setTimestamp(int i, Timestamp v, Calendar c) throws SQLException { setTimestamp(i, v); }

    public void setObject(int i, Object v) throws SQLException {
        switch (v) {
            case Date d -> setDate(i, d);
            case Time t -> setTime(i, t);
            case Timestamp t -> setTimestamp(i, t);
            case Character c -> set(i, c.toString());
            case java.util.UUID u -> set(i, u.toString());
            case java.time.Instant t -> set(i, t.toString());
            case java.time.LocalDateTime t -> set(i, java.time.format.DateTimeFormatter.ISO_LOCAL_DATE_TIME.format(t));
            case java.time.LocalTime t -> set(i, java.time.format.DateTimeFormatter.ISO_LOCAL_TIME.format(t));
            case java.time.OffsetDateTime t -> set(i, java.time.format.DateTimeFormatter.ISO_OFFSET_DATE_TIME.format(t));
            case java.time.ZonedDateTime t ->
                    set(i, java.time.format.DateTimeFormatter.ISO_OFFSET_DATE_TIME.format(t.toOffsetDateTime()));
            case java.time.temporal.TemporalAccessor t -> set(i, t.toString());
            case null, default -> set(i, v);
        }
    }

    public void setObject(int i, Object v, int sqlType) throws SQLException { setObject(i, v); }
    public void setObject(int i, Object v, int sqlType, int scale) throws SQLException { setObject(i, v); }

    public void setCharacterStream(int i, Reader r) throws SQLException { set(i, read(r)); }
    public void setCharacterStream(int i, Reader r, int len) throws SQLException { set(i, read(r)); }
    public void setCharacterStream(int i, Reader r, long len) throws SQLException { set(i, read(r)); }
    public void setBinaryStream(int i, InputStream in) throws SQLException { set(i, read(in)); }
    public void setBinaryStream(int i, InputStream in, int len) throws SQLException { set(i, read(in)); }
    public void setBinaryStream(int i, InputStream in, long len) throws SQLException { set(i, read(in)); }

    private static String read(Reader r) throws SQLException {
        if (r == null) return null;
        try {
            StringBuilder sb = new StringBuilder();
            char[] buf = new char[8192];
            int n;
            while ((n = r.read(buf)) > 0) sb.append(buf, 0, n);
            return sb.toString();
        } catch (IOException e) {
            throw new SQLException(e);
        }
    }

    private static byte[] read(InputStream in) throws SQLException {
        if (in == null) return null;
        try {
            return in.readAllBytes();
        } catch (IOException e) {
            throw new SQLException(e);
        }
    }

    // ---------------------------------------------------------------- misc

    public void close() throws SQLException {
        if (closed) return;
        closeCurrentResultSet();
        closed = true;
    }

    public boolean isClosed() {
        return closed;
    }

    void checkOpen() throws SQLException {
        if (closed) throw new SQLException("statement is closed");
        conn.checkOpen();
    }

    public Connection getConnection() {
        return conn.proxy();
    }

    public void cancel() throws SQLException {
        throw new SQLFeatureNotSupportedException("cancel is not supported by the libSQL HTTP driver");
    }

    public int getMaxRows() { return (int) maxRows; }
    public void setMaxRows(int max) { maxRows = Math.max(0, max); }
    public long getLargeMaxRows() { return maxRows; }
    public void setLargeMaxRows(long max) { maxRows = Math.max(0, max); }
    public int getMaxFieldSize() { return 0; }
    public void setMaxFieldSize(int max) { }
    public int getQueryTimeout() { return queryTimeout; }
    public void setQueryTimeout(int seconds) { queryTimeout = seconds; }
    public int getFetchSize() { return fetchSize; }
    public void setFetchSize(int rows) { fetchSize = rows; }
    public int getFetchDirection() { return fetchDirection; }
    public void setFetchDirection(int d) { fetchDirection = d; }
    public int getResultSetType() { return resultSetType; }
    public int getResultSetConcurrency() { return ResultSet.CONCUR_READ_ONLY; }
    public int getResultSetHoldability() { return ResultSet.CLOSE_CURSORS_AT_COMMIT; }
    public SQLWarning getWarnings() { return null; }
    public void clearWarnings() { }
    public void setEscapeProcessing(boolean enable) { }
    public boolean isPoolable() { return poolable; }
    public void setPoolable(boolean p) { poolable = p; }
    public void closeOnCompletion() { closeOnCompletion = true; }
    public boolean isCloseOnCompletion() { return closeOnCompletion; }

    @Override
    public String toString() {
        return sql == null ? "Statement" : HranaClient.abbreviate(sql);
    }
}
